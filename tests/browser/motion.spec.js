import { test, expect } from '@playwright/test';

test('compact copy, local focus indicators and stat card tilt/reset', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'no-preference', colorScheme: 'light' });
  await page.goto('/');
  await expect(page.locator('.historystats .stat-card')).toHaveCount(4);
  await expect(page.locator('body')).not.toContainText('价格与价值，一目了然');
  await expect(page.locator('body')).not.toContainText('看清每一段价格偏离');
  await expect(page.locator('body')).not.toContainText('选择最多 4 只基金，比较历史走势');
  await expect(page.locator('body')).not.toContainText('虚线为零溢价');
  const gauge = page.locator('#vix-gauge');
  await gauge.click();
  expect(await gauge.evaluate(el => getComputedStyle(el).outlineStyle)).toBe('none');
  const search = page.getByRole('searchbox', { name: '搜索基金' });
  await search.click();
  expect(await search.evaluate(el => getComputedStyle(el).outlineStyle)).toBe('none');
  const start = page.getByLabel('起始日期');
  await start.focus();
  expect(await start.evaluate(el => getComputedStyle(el).outlineStyle)).toBe('none');
  const card = page.locator('.historystats .stat-card').first();
  await card.scrollIntoViewIfNeeded();
  await page.mouse.move(5, 5);
  const before = await card.boundingBox();
  const shell = page.locator('.historystats .stat-card-shell').first();
  const box = await shell.boundingBox();
  await page.mouse.move(box.x + box.width * .75, box.y + box.height * .25);
  await expect.poll(async () => (await card.boundingBox()).y).toBeLessThan(before.y - 3);
  await expect.poll(() => card.evaluate(el => getComputedStyle(el).transform)).toContain('matrix3d');
  await page.screenshot({ path: 'test-results/stat-card-hover.png' });
  await page.mouse.move(5, 5);
  await expect.poll(async () => Math.abs((await card.boundingBox()).y - before.y)).toBeLessThan(.5);
  await page.getByRole('button', { name: '1个月', exact: true }).click();
  await expect(page.locator('.chart-series')).toHaveCount(3);
  await page.getByRole('link', { name: '美国重要日期', exact: true }).last().click();
  await expect(page.locator('.calendar-cell')).toHaveCount(42);
  await expect(page.locator('body')).not.toContainText('重要时刻，提前看见');
  await expect(page.locator('body')).not.toContainText('THE MARKET CALENDAR');
  const zone = page.getByLabel('日历时区');
  await zone.focus();
  expect(await zone.evaluate(el => getComputedStyle(el).outlineStyle)).toBe('none');
  await page.getByRole('button', { name: '下个月', exact: true }).click();
  await expect(page.locator('.calendar-cell')).toHaveCount(42);
  await expect(page.locator('.month-navigation h2')).toContainText('11 月');
  expect(errors).toEqual([]);
});

test('reduced motion keeps cards stable and chart data visible', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  const card = page.locator('.historystats .stat-card').first();
  await expect(card).toBeVisible();
  await card.scrollIntoViewIfNeeded();
  const before = await card.boundingBox();
  await card.hover({ position: { x: 20, y: 20 } });
  expect(Math.abs((await card.boundingBox()).y - before.y)).toBeLessThan(.1);
  expect(await card.evaluate(el => getComputedStyle(el).transform)).toBe('none');
  await page.getByRole('button', { name: '1个月', exact: true }).click();
  const path = page.locator('.chart-series').first();
  await expect(path).toBeVisible();
  await expect(path).toHaveCSS('opacity', '1');
  await expect.poll(() => path.evaluate(el => parseFloat(getComputedStyle(el).strokeDashoffset))).toBe(0);
});
